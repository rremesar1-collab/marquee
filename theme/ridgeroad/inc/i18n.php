/** Hand the translations to the scripts (before any of them run). */
function ridgeroad_js_i18n_print() {
	$m = ridgeroad_js_strings();
	if ( function_exists( 'marquee_js_strings' ) ) {
		$m = array_merge( $m, marquee_js_strings() );
	}
	if ( $m ) {
		echo '<script>window.rrI18n=' . wp_json_encode( $m ) . ';</script>' . "\n";
	}
}
add_action( 'wp_head', 'ridgeroad_js_i18n_print', 1 );
add_action( 'admin_head', 'ridgeroad_js_i18n_print', 1 );
